"""Generate documentation from Python docstrings and comments."""

import ast
from pathlib import Path

from anima import Context, Service


class GenerateDocsService(Service):
    """Generate documentation from Python docstrings and comments.

    Creates a markdown summary of all public functions and classes found
    in Python files under the given directory.

    Args:
        path: Directory to generate docs for (defaults to '.').

    Returns:
        Markdown documentation with signatures and docstrings.
    """

    def __init__(self, ctx: Context):
        super().__init__(ctx, "generate_docs")

    def __call__(
        self,
        *,
        path: str = ".",
        read_files: set[str] | None = None,
    ) -> str:
        root = Path(path)
        py_files = list(root.rglob("*.py"))

        docs_lines: list[str] = []
        docs_lines.append(f"# Auto-generated Documentation for {path}")
        docs_lines.append("")
        docs_lines.append("_Generated by magecode recursive improvement tools_")
        docs_lines.append("")

        for py_file in py_files:
            try:
                text = py_file.read_text(encoding="utf-8")
                tree = ast.parse(text)
            except (OSError, UnicodeDecodeError, SyntaxError):
                continue

            filename = py_file.name
            docs_lines.append(f"## {filename}")
            docs_lines.append("")

            for node in ast.iter_child_nodes(tree):
                if isinstance(node, ast.ClassDef):
                    class_doc = ast.get_docstring(node) or ""
                    docs_lines.append(f"### {node.name}")
                    if class_doc:
                        docs_lines.append(f"*{class_doc}*")
                    else:
                        docs_lines.append("_No docstring_")
                    docs_lines.append("")

                    for item in node.body:
                        if isinstance(item, ast.FunctionDef):
                            func_doc = ast.get_docstring(item) or ""
                            docs_lines.append(f"- **{item.name}(...)**")
                            if func_doc:
                                docs_lines.append(f"  *{func_doc}*")
                            else:
                                docs_lines.append("  _No docstring_")
                            docs_lines.append("")

                elif isinstance(node, ast.FunctionDef):
                    func_doc = ast.get_docstring(node) or ""
                    docs_lines.append(f"- **{node.name}(...)**")
                    if func_doc:
                        docs_lines.append(f"  *{func_doc}*")
                    else:
                        docs_lines.append("  _No docstring_")
                    docs_lines.append("")

        return "\n".join(docs_lines)
